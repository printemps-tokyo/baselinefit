//! baselinefit -- audit a codebase against Web Platform Baseline, both ways.
//!
//! # Two questions, not one
//!
//! Every tool that knows about Baseline answers the same question: *is this
//! feature safe to use yet?* Editors underline it, linters fail on it,
//! `browserslist` encodes it. That is the forward direction, and it is well
//! served.
//!
//! Nothing answers the other one: *which of the things I wrote because a
//! feature was not safe can I finally delete?* The `-webkit-` prefixes, the
//! `@supports` guards that always pass now, the polyfill that ships on every
//! page for a browser nobody has. Those accumulate silently, and they never
//! trip a linter, because there is nothing wrong with them -- they are just no
//! longer doing anything.
//!
//! baselinefit answers both, from the same dataset and the same `--target`.
//!
//! # Baseline
//!
//! Baseline (<https://web.dev/baseline>, read 2026-08-12) describes a feature
//! as *Newly available* once "the feature is supported by all of the core
//! browsers, and is therefore interoperable", and *Widely available* once "30
//! months have passed since the newly interoperable date". Features that became
//! Newly available in a given calendar year are collectively "Baseline 2025",
//! and so on. `--target` accepts exactly those three shapes, matching the
//! Browserslist queries documented at
//! <https://web.dev/articles/use-baseline-with-browserslist> (read 2026-08-12).
//!
//! # Where the data comes from
//!
//! `src/features.json` is generated by `tools/fetch-data.py` from the published
//! `web-features` npm package, and every status and date in it is copied
//! verbatim. The version, the tarball URL, its SHA-256 and the retrieval date
//! are stamped into the file and printed under every report. It is a snapshot:
//! re-run the generator to refresh it.
//!
//! # What it is not
//!
//! It does not parse your code. Matching is literal text, line by line, with a
//! documented boundary rule per detector kind (see [`matcher`]). A hit inside a
//! comment, a string or a vendored stylesheet is reported like any other. That
//! is a deliberate trade: a textual matcher works on CSS, Sass, HTML, JSX and
//! template languages alike, and the alternative -- a parser per dialect --
//! would cover less, not more. `--exclude` and the `baselinefit:ignore` marker
//! are how you deal with the noise.
//!
//! # Shape
//!
//! - [`catalog::Catalog`] is data, parsed from the embedded snapshot.
//! - [`target::Target`] turns `--target` into a single predicate.
//! - [`matcher::Matcher`] is pure: a catalog plus a target plus text in,
//!   [`matcher::Hit`]s out.
//! - [`model::Report::build`] is pure: hits in, a grouped and judged report out.
//! - [`report`] renders text or JSON.
//! - [`scan`] is the only module that touches the filesystem.
//!
//! No network access happens at any point.
//!
//! ```no_run
//! use baselinefit::{catalog::Catalog, matcher::Matcher, model::Report, report, scan, target::Target};
//!
//! let catalog = Catalog::builtin();
//! let matcher = Matcher::new(&catalog, Target::Widely)?;
//! let (hits, stats) = scan::scan_tree(
//!     std::path::Path::new("."),
//!     &scan::ScanOptions::default(),
//!     &matcher,
//! )?;
//! let report = Report::build("my-site".into(), Target::Widely, None, &catalog, hits, stats);
//! print!("{}", report::render_text(&report, report::RenderOptions::default()));
//! # Ok::<(), String>(())
//! ```

